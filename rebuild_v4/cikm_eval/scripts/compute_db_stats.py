"""
Compute EXP-DB statistics for the CIKM demo paper.

Reads:
  - processed_attributes_500recipes.jsonl  (raw post-extraction, pre-blacklist)
  - food-exhibit-data-500recipes.json      (post-normalization + post-blacklist, used in demo)

Writes:
  - tables/db_stats.tex  (LaTeX booktabs table)
  - eval_data/db_stats.json  (machine-readable stats for downstream scripts)

Metrics reported follow standard descriptive statistics for IE datasets
(see e.g., Zhang et al. 2022 ABSA survey, Sec. 2 on benchmark statistics).
"""
import json
from collections import Counter, defaultdict
from pathlib import Path
from statistics import mean, median

ROOT = Path(__file__).resolve().parents[2]
RAW_FILE = ROOT / "processed_attributes_500recipes.jsonl"
EXHIBIT_FILE = ROOT / "food-exhibit-data-500recipes.json"
OUT_TEX = Path(__file__).resolve().parents[1] / "tables" / "db_stats.tex"
OUT_JSON = Path(__file__).resolve().parents[1] / "eval_data" / "db_stats.json"

DIMS = [
    "taste_flavor",
    "texture_mouthfeel",
    "meal_type",
    "occasion_holiday",
    "audience_enjoyment",
    "cuisine_type",
]

DIM_DISPLAY = {
    "taste_flavor": "Flavor",
    "texture_mouthfeel": "Texture",
    "meal_type": "Meal Type",
    "occasion_holiday": "Occasion",
    "audience_enjoyment": "Audience",
    "cuisine_type": "Cuisine Type",
}

# Field in exhibit json that holds the post-normalization canonical list per recipe.
EXHIBIT_FIELD = {
    "taste_flavor": "taste_attributes",
    "texture_mouthfeel": "texture_attributes",
    "meal_type": "meal_type_attributes",
    "occasion_holiday": "occasion_attributes",
    "audience_enjoyment": "audience_attributes",
    "cuisine_type": "type_attributes",
}


def load_raw():
    rows = []
    with open(RAW_FILE) as f:
        for line in f:
            rows.append(json.loads(line))
    return rows


def raw_stats(rows):
    recipes = {r["recipe_id"] for r in rows}
    n_reviews = len(rows)
    attrs_per_review = [len(r.get("attributes", [])) for r in rows]
    total_attrs = sum(attrs_per_review)
    spans_valid = 0
    per_dim_count = Counter()
    per_dim_entities = defaultdict(Counter)
    for r in rows:
        for a in r.get("attributes", []):
            sp = a.get("span", {})
            if sp.get("end", 0) > sp.get("start", -1):
                spans_valid += 1
            d = a.get("dimension")
            per_dim_count[d] += 1
            per_dim_entities[d][a.get("entity", "").strip().lower()] += 1
    return {
        "n_recipes": len(recipes),
        "n_reviews": n_reviews,
        "total_attrs": total_attrs,
        "attrs_per_review_mean": mean(attrs_per_review),
        "attrs_per_review_median": median(attrs_per_review),
        "span_groundedness_pct": 100.0 * spans_valid / max(total_attrs, 1),
        "per_dim_count": dict(per_dim_count),
        "per_dim_unique_entities": {d: len(per_dim_entities[d]) for d in per_dim_count},
    }


def exhibit_stats():
    with open(EXHIBIT_FILE) as f:
        data = json.load(f)
    items = data["items"]
    n_items = len(items)
    per_dim_unique_canonical = {}
    per_dim_top10_coverage = {}
    per_dim_total_occurrences = {}
    for dim in DIMS:
        field = EXHIBIT_FIELD[dim]
        counter = Counter()
        # exhibit aggregates per-recipe; for top-k coverage we count occurrences across recipes
        for item in items:
            for v in item.get(field, []) or []:
                counter[v.lower()] += 1
        total = sum(counter.values())
        top10 = sum(c for _, c in counter.most_common(10))
        per_dim_unique_canonical[dim] = len(counter)
        per_dim_total_occurrences[dim] = total
        per_dim_top10_coverage[dim] = 100.0 * top10 / max(total, 1)
    return {
        "n_items": n_items,
        "per_dim_unique_canonical": per_dim_unique_canonical,
        "per_dim_top10_coverage_pct": per_dim_top10_coverage,
        "per_dim_total_canonical_occurrences": per_dim_total_occurrences,
    }


def emit_tex(raw, ex):
    lines = []
    a = lines.append
    a("% Auto-generated by scripts/compute_db_stats.py. Do not edit by hand.")
    a("\\begin{table}[t]")
    a("\\centering")
    a("\\small")
    a("\\begin{tabular}{@{}lrrrrr@{}}")
    a("\\toprule")
    a("\\textbf{Dimension} & \\textbf{Extr.} & \\textbf{Raw} & \\textbf{Canon.} & \\textbf{Comp.} & \\textbf{Top-10} \\\\")
    a(" & & \\textbf{entities} & \\textbf{forms} & \\textbf{ratio} & \\textbf{cov.\\%} \\\\")
    a("\\midrule")
    for d in DIMS:
        raw_c = raw["per_dim_count"].get(d, 0)
        raw_e = raw["per_dim_unique_entities"].get(d, 0)
        can_e = ex["per_dim_unique_canonical"].get(d, 0)
        ratio = raw_e / max(can_e, 1)
        cov = ex["per_dim_top10_coverage_pct"].get(d, 0)
        a(f"{DIM_DISPLAY[d]} & {raw_c:,} & {raw_e:,} & {can_e:,} & {ratio:.1f}$\\times$ & {cov:.1f}\\\\")
    a("\\midrule")
    total_extr = sum(raw["per_dim_count"].values())
    a(f"\\textbf{{All}} & \\textbf{{{total_extr:,}}} & -- & -- & -- & -- \\\\")
    a("\\bottomrule")
    a("\\end{tabular}")
    cap = (
        f"EXP-DB statistics. We process {raw['n_reviews']:,} reviews across "
        f"{raw['n_recipes']:,} recipes, yielding {total_extr:,} raw extracted attribute mentions. "
        f"Spans are valid by construction ({raw['span_groundedness_pct']:.0f}\\% span-groundedness "
        f"after the FindSpan filter in Section~\\ref{{sec:extraction}}). "
        "\\emph{Comp.\\ ratio} = raw unique entities / canonical forms after the agentic "
        "normalization loop. \\emph{Top-10 cov.\\%} reports the fraction of canonical occurrences "
        "covered by the ten most frequent canonical forms per dimension, a common faceted-search "
        "usability indicator~\\cite{hearst2009search}."
    )
    a("\\caption{" + cap + "}")
    a("\\label{tab:db-stats}")
    a("\\end{table}")
    OUT_TEX.parent.mkdir(parents=True, exist_ok=True)
    OUT_TEX.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT_TEX}")


def main():
    rows = load_raw()
    raw = raw_stats(rows)
    ex = exhibit_stats()
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    OUT_JSON.write_text(json.dumps({"raw": raw, "exhibit": ex}, indent=2))
    emit_tex(raw, ex)

    print("\n=== Database Statistics ===")
    print(json.dumps({"raw": raw, "exhibit": ex}, indent=2))


if __name__ == "__main__":
    main()
