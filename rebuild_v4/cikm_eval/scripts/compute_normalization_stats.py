"""
Normalization effectiveness for the agentic loop.

Reports per dimension:
  - #raw unique entities
  - #canonical forms after the agent skill converges
  - Compression ratio
  - Top-10 coverage% (faceted-UI usability, Hearst 2009)
  - Top-30 coverage% (skill convergence criterion: target >= 80%)
  - Whether top-30 >= 80% (skill considers the category converged)

This is descriptive evaluation -- no LLM calls.
"""
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
EXHIBIT_FILE = ROOT / "food-exhibit-data-500recipes.json"
RAW_FILE = ROOT / "processed_attributes_500recipes.jsonl"
OUT_TEX = Path(__file__).resolve().parents[1] / "tables" / "normalization.tex"

DIMS = [
    "taste_flavor",
    "texture_mouthfeel",
    "meal_type",
    "occasion_holiday",
    "audience_enjoyment",
    "cuisine_type",
]
DIM_DISPLAY = {
    "taste_flavor": "Flavor",
    "texture_mouthfeel": "Texture",
    "meal_type": "Meal Type",
    "occasion_holiday": "Occasion",
    "audience_enjoyment": "Audience",
    "cuisine_type": "Cuisine Type",
}
EXHIBIT_FIELD = {
    "taste_flavor": "taste_attributes",
    "texture_mouthfeel": "texture_attributes",
    "meal_type": "meal_type_attributes",
    "occasion_holiday": "occasion_attributes",
    "audience_enjoyment": "audience_attributes",
    "cuisine_type": "type_attributes",
}


def load_raw_unique_entities():
    counts = {d: Counter() for d in DIMS}
    with open(RAW_FILE) as f:
        for line in f:
            r = json.loads(line)
            for a in r.get("attributes", []):
                d = a.get("dimension")
                if d in counts:
                    counts[d][a.get("entity", "").strip().lower()] += 1
    return counts


def load_canonical_counts():
    counters = {d: Counter() for d in DIMS}
    with open(EXHIBIT_FILE) as f:
        data = json.load(f)
    for item in data["items"]:
        for d in DIMS:
            for v in item.get(EXHIBIT_FIELD[d], []) or []:
                counters[d][v.lower()] += 1
    return counters


def top_k_coverage(counter: Counter, k: int) -> float:
    total = sum(counter.values())
    if total == 0:
        return 0.0
    top = sum(c for _, c in counter.most_common(k))
    return 100.0 * top / total


def main():
    raw = load_raw_unique_entities()
    canon = load_canonical_counts()
    rows = []
    for d in DIMS:
        raw_unique = len(raw[d])
        canon_unique = len(canon[d])
        ratio = raw_unique / max(canon_unique, 1)
        top10 = top_k_coverage(canon[d], 10)
        top30 = top_k_coverage(canon[d], 30)
        converged = "\\checkmark" if top30 >= 80.0 else ""
        rows.append((d, raw_unique, canon_unique, ratio, top10, top30, converged))

    lines = []
    a = lines.append
    a("% Auto-generated by scripts/compute_normalization_stats.py")
    a("\\begin{table}[t]")
    a("\\centering")
    a("\\small")
    a("\\begin{tabular}{@{}lrrrrrc@{}}")
    a("\\toprule")
    a("\\textbf{Dimension} & \\textbf{Raw} & \\textbf{Canon.} & \\textbf{Comp.} & \\textbf{Top-10} & \\textbf{Top-30} & \\textbf{Conv.} \\\\")
    a(" & \\textbf{ent.} & \\textbf{forms} & \\textbf{ratio} & \\textbf{cov.\\%} & \\textbf{cov.\\%} & \\\\")
    a("\\midrule")
    for d, ru, cu, ratio, t10, t30, conv in rows:
        a(f"{DIM_DISPLAY[d]} & {ru:,} & {cu:,} & {ratio:.1f}$\\times$ & {t10:.1f} & {t30:.1f} & {conv} \\\\")
    a("\\bottomrule")
    a("\\end{tabular}")
    cap = (
        "Effectiveness of the agentic normalization loop. \\emph{Comp.\\ ratio} is the raw-to-canonical "
        "fragmentation reduction. \\emph{Top-30 cov.} is the convergence criterion of the loop "
        "(target $\\geq 80\\%$); a checkmark in \\emph{Conv.} indicates the dimension converged. "
        "Dimensions with broader expressive space (Flavor, Texture) plateau below 80\\%, "
        "consistent with Zipfian long tails in opinion text~\\cite{zhang2022survey}."
    )
    a("\\caption{" + cap + "}")
    a("\\label{tab:normalization}")
    a("\\end{table}")
    OUT_TEX.write_text("\n".join(lines) + "\n")
    print(f"Wrote {OUT_TEX}")

    print("\n=== Normalization Effectiveness ===")
    for d, ru, cu, ratio, t10, t30, conv in rows:
        print(f"  {DIM_DISPLAY[d]:13s} raw={ru:5d} canon={cu:4d} ratio={ratio:5.1f}x  top10={t10:5.1f}% top30={t30:5.1f}% conv={'YES' if conv else 'no'}")


if __name__ == "__main__":
    main()
