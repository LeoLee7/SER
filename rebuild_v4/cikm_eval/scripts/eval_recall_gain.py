"""
Concept-coverage gain from extraction + normalization (selling point 2 -> 3).

Plain idea: people express the same concept many ways ("mom", "mum", "mommy" all
mean mother; "hubby", "DH" mean husband). A literal keyword search for the word
"mother" only finds reviews that contain that exact word. SER indexes the CONCEPT
(the canonical facet "mother"), because the LLM extraction maps "mom"->mother and
our synonym loop maps "DH"->husband. So the SER facet surfaces recipes a literal
search would miss.

We quantify this as COVERAGE EXPANSION (deterministic, no LLM judge):
  keyword(c)  = # recipes whose reviews literally contain the word c (whole-word)
  ser(c)      = # recipes that carry the canonical facet c (any surface form)
  expansion   = ser(c) / keyword(c)
  missed_by_keyword = (ser - keyword_and_ser) / ser   # share of SER recipes a
                                                       # literal search misses

This is a coverage comparison, NOT a recall-against-SER-gold (which would be
circular). It simply shows how many additional recipes the concept-level index
surfaces over exact-word matching.

Output: tables/recall_gain.tex  +  console summary.
"""
import json, re
from collections import defaultdict
from pathlib import Path

ROOT = Path("/Users/liliu/SER-DB")
PAPER = Path(__file__).resolve().parents[1]
TABLES = PAPER / "tables"
PROC = Path("/Users/liliu/subjective_DB/spn_datasets/food/phase3_llm_extraction/data/processed_attributes_500recipes.jsonl")

DIM_DISPLAY = {
    "taste_flavor":"Flavor","texture_mouthfeel":"Texture","meal_type":"Meal Type",
    "occasion_holiday":"Occasion","audience_enjoyment":"Audience","cuisine_type":"Cuisine",
}

# Curated high-value concepts to report (canonical forms that exist in the data).
CONCEPTS = [
    ("audience_enjoyment","mother"),
    ("audience_enjoyment","husband"),
    ("audience_enjoyment","kids"),
    ("audience_enjoyment","daughter"),
    ("taste_flavor","spicy"),
    ("taste_flavor","sweet"),
    ("cuisine_type","mediterranean"),
    ("meal_type","dinner"),
]


def load():
    recipe_canon = defaultdict(lambda: defaultdict(set))  # rid -> dim -> set(canonical)
    recipe_reviews = defaultdict(list)                    # rid -> [review_text lower]
    variants = defaultdict(lambda: defaultdict(set))      # dim -> canonical -> set(surface forms seen)
    seen_review = set()
    for line in open(PROC):
        r = json.loads(line); rid = r["recipe_id"]; ridx = r["review_idx"]
        if (rid,ridx) not in seen_review:
            recipe_reviews[rid].append(r["review_text"].lower()); seen_review.add((rid,ridx))
        for a in r["attributes"]:
            d = a["dimension"]
            ne = (a.get("normalized_entity") or "").strip().lower()
            e = (a.get("entity") or "").strip().lower()
            if not ne: continue
            recipe_canon[rid][d].add(ne)
            variants[d][ne].add(e)
    return recipe_canon, recipe_reviews, variants


def recipes_with_facet(recipe_canon, dim, canon):
    return {rid for rid,dd in recipe_canon.items() if canon in dd.get(dim,set())}


def recipes_with_literal(recipe_reviews, word):
    pat = re.compile(r"\b" + re.escape(word.replace("-"," ")) + r"\b")
    pat2 = re.compile(r"\b" + re.escape(word) + r"\b")
    out = set()
    for rid, revs in recipe_reviews.items():
        if any(pat.search(t) or pat2.search(t) for t in revs):
            out.add(rid)
    return out


def main():
    recipe_canon, recipe_reviews, variants = load()
    rows = []
    for dim, canon in CONCEPTS:
        ser = recipes_with_facet(recipe_canon, dim, canon)
        kw = recipes_with_literal(recipe_reviews, canon)
        kw_in_ser = kw & ser
        missed = len(ser) - len(kw_in_ser)
        miss_pct = 100*missed/len(ser) if ser else 0
        exp = len(ser)/len(kw_in_ser) if kw_in_ser else float("inf")
        surface = sorted(v for v in variants[dim][canon] if v != canon)[:4]
        rows.append((dim, canon, len(kw_in_ser), len(ser), exp, miss_pct, surface))

    # table
    L=[]; a=L.append
    a("% Auto-generated by scripts/eval_recall_gain.py")
    a("\\begin{table}[t]"); a("\\centering"); a("\\small"); a("\\setlength{\\tabcolsep}{4pt}")
    a("\\begin{tabular}{@{}llrrr@{}}")
    a("\\toprule")
    a("\\textbf{Dim} & \\textbf{Concept} & \\textbf{Keyword} & \\textbf{SER} & \\textbf{Missed by} \\\\")
    a(" & & \\textbf{(exact word)} & \\textbf{(facet)} & \\textbf{keyword \\%} \\\\")
    a("\\midrule")
    tot_kw=tot_ser=0
    for dim,canon,kw,ser,exp,miss,surf in rows:
        tot_kw+=kw; tot_ser+=ser
        a(f"{DIM_DISPLAY[dim][:4]} & {canon} & {kw} & {ser} & {miss:.0f} \\\\")
    a("\\midrule")
    macro_miss = 100*(tot_ser-tot_kw)/tot_ser if tot_ser else 0
    a(f"\\textbf{{Total}} & & \\textbf{{{tot_kw}}} & \\textbf{{{tot_ser}}} & \\textbf{{{macro_miss:.0f}}} \\\\")
    a("\\bottomrule"); a("\\end{tabular}")
    a("\\caption{Concept-coverage gain from SER's extraction + normalization. "
      "\\emph{Keyword} = recipes whose reviews contain the exact concept word; "
      "\\emph{SER} = recipes carrying the canonical facet (any surface form, e.g.\\ "
      "mom/mum/mommy for \\emph{mother}, DH/hubby for \\emph{husband}). "
      "\\emph{Missed by keyword \\%} is the share of SER-surfaced recipes that an "
      "exact-word search would not return. A literal keyword search misses a large "
      "fraction of relevant recipes because users express the same concept with many "
      "surface forms; SER's concept-level index recovers them.}")
    a("\\label{tab:recall-gain}"); a("\\end{table}")
    TABLES.mkdir(parents=True,exist_ok=True)
    (TABLES/"recall_gain.tex").write_text("\n".join(L)+"\n")
    print(f"Wrote {TABLES/'recall_gain.tex'}\n")

    print(f"{'concept':28s} {'keyword':>8s} {'SER':>6s} {'×':>5s} {'missed%':>8s}  surface forms")
    for dim,canon,kw,ser,exp,miss,surf in rows:
        e = f"{exp:.1f}" if exp!=float('inf') else 'inf'
        print(f"{DIM_DISPLAY[dim]+'/'+canon:28s} {kw:8d} {ser:6d} {e:>5s} {miss:7.0f}%  {surf}")
    print(f"\nTotal: keyword finds {tot_kw}, SER finds {tot_ser} -> keyword misses {macro_miss:.0f}% of SER-surfaced recipes")


if __name__=="__main__":
    main()
