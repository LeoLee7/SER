"""
Two coverage-growth tables (gold-free): absolute counts and a base-100 index.

Without a ground-truth gold we cannot compute true recall. We instead report the
observable number of recipes each pipeline stage surfaces, summed over the top-20
canonical concepts per category, across:
    Keyword (exact word) -> + LLM extraction -> Full SER (after normalization)

Table 1 (absolute): the raw counts and the extra recipes SER finds over keyword.
Table 2 (relative): the same, indexed to the keyword baseline = 100 (a base-100
index, as used for CPI / stock indices), so each stage reads as a percentage uplift.
This is the standard "relative improvement over baseline" / lift framing
(lift = method / baseline; Tan, Steinbach & Kumar, Introduction to Data Mining).

A separate pooled, judged study (tables/pr_trajectory.tex) shows precision is
constant across these stages, so the coverage growth is genuine recall, not noise.

Counts are concept-recipe memberships (a recipe counted once per concept it carries).

Reads eval_data/coverage_global.json ; writes tables/coverage_abs.tex and
tables/coverage_rel.tex.
"""
import json
from collections import defaultdict
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
d = json.load(open(PAPER/"eval_data"/"coverage_global.json"))
DISP = {"taste_flavor":"Flavor","texture_mouthfeel":"Texture","meal_type":"Meal",
        "occasion_holiday":"Occasion","audience_enjoyment":"Audience","cuisine_type":"Cuisine"}
REP  = {"taste_flavor":"sweet","texture_mouthfeel":"moist","meal_type":"dinner",
        "occasion_holiday":"christmas","audience_enjoyment":"mother","cuisine_type":"italian"}
ORDER = ["taste_flavor","texture_mouthfeel","meal_type","occasion_holiday","audience_enjoyment","cuisine_type"]

bycat = defaultdict(list)
for r in d: bycat[r["dim"]].append(r)
idx = {(r["dim"], r["concept"]): r for r in d}

def sums(dim):
    rs = [r for r in bycat[dim] if r["v1"]>0]
    return (sum(r["kw"] for r in rs), sum(r["gemma"] for r in rs), sum(r["v1"] for r in rs))

S = {dim: sums(dim) for dim in ORDER}
TK = sum(S[d_][0] for d_ in ORDER); TE = sum(S[d_][1] for d_ in ORDER); TV = sum(S[d_][2] for d_ in ORDER)

# ---------- Table 1: absolute ----------
L=[]; a=L.append
a("% Auto-generated by scripts/make_coverage_trend_table.py")
a("\\begin{table}[t]"); a("\\centering"); a("\\small"); a("\\setlength{\\tabcolsep}{4pt}")
a("\\begin{tabular}{@{}llrrrr@{}}")
a("\\toprule")
a("\\textbf{Category} & \\textbf{Example concept} & \\textbf{Keyword} & \\textbf{+ Extraction} & \\textbf{Full SER} & \\textbf{Extra} \\\\")
a("\\midrule")
for dim in ORDER:
    skw,sext,sv1 = S[dim]; rc = idx[(dim,REP[dim])]
    ex = f"{REP[dim]} ({rc['kw']}$\\to${rc['v1']})"
    a(f"{DISP[dim]} & {ex} & {skw:,} & {sext:,} & {sv1:,} & +{sv1-skw:,} \\\\")
a("\\midrule")
a(f"\\textbf{{All (120 concepts)}} & & \\textbf{{{TK:,}}} & \\textbf{{{TE:,}}} & \\textbf{{{TV:,}}} & \\textbf{{+{TV-TK:,}}} \\\\")
a("\\bottomrule"); a("\\end{tabular}")
a("\\caption{Recipes surfaced (concept-recipe memberships), summed over the top-20 "
  "canonical concepts per category, as the pipeline is built up: literal keyword match, "
  "after LLM extraction, and the deployed SER facet (after normalization). "
  "\\emph{Extra} is the additional recipes SER surfaces over a literal keyword search. "
  "No ground-truth gold is needed; these are observed counts. Extraction is selective "
  "and roughly coverage-neutral; normalization drives the gain, which concentrates in "
  "high-variation categories (Audience $+977$, Meal $+454$) and is small where reviewers "
  "already use the canonical word (Flavor $+84$, Texture $+80$). A pooled judged study "
  "(Table~\\ref{tab:pr-trajectory}) confirms precision is constant across these stages, so "
  "the added coverage is genuine recall.}")
a("\\label{tab:coverage-abs}"); a("\\end{table}")
(PAPER/"tables"/"coverage_abs.tex").write_text("\n".join(L)+"\n")

# ---------- Table 2: relative (base-100 index) ----------
def pct(n,base): return 100.0*n/base
L=[]; a=L.append
a("% Auto-generated by scripts/make_coverage_trend_table.py")
a("\\begin{table}[t]"); a("\\centering"); a("\\small"); a("\\setlength{\\tabcolsep}{5pt}")
a("\\begin{tabular}{@{}lrrrr@{}}")
a("\\toprule")
a("\\textbf{Category} & \\textbf{Keyword} & \\textbf{+ Extraction} & \\textbf{Full SER} & \\textbf{Uplift} \\\\")
a("\\midrule")
for dim in ORDER:
    skw,sext,sv1 = S[dim]
    a(f"{DISP[dim]} & 100 & {pct(sext,skw):.0f} & {pct(sv1,skw):.0f} & +{pct(sv1-skw,skw):.0f}\\% \\\\")
a("\\midrule")
a(f"\\textbf{{All}} & 100 & {pct(TE,TK):.0f} & \\textbf{{{pct(TV,TK):.0f}}} & \\textbf{{+{pct(TV-TK,TK):.0f}\\%}} \\\\")
a("\\bottomrule"); a("\\end{tabular}")
a("\\caption{The same coverage indexed to the keyword baseline ($=100$), a base-100 "
  "index in the spirit of relative-improvement-over-baseline / lift reporting "
  "(lift $=$ method$/$baseline). Each cell is the share of recipes a stage surfaces "
  "relative to a literal keyword search. \\emph{Uplift} is Full SER over keyword. "
  "SER surfaces $+15\\%$ more recipes overall, rising to $+45\\%$ for Meal and $+34\\%$ "
  "for Audience, and only $+2$--$4\\%$ for Flavor and Texture where the canonical word "
  "is already what reviewers write.}")
a("\\label{tab:coverage-rel}"); a("\\end{table}")
(PAPER/"tables"/"coverage_rel.tex").write_text("\n".join(L)+"\n")

print("Wrote tables/coverage_abs.tex and tables/coverage_rel.tex\n")
print("ABSOLUTE:")
print(f"  {'Category':9s} {'Keyword':>8s} {'+Extract':>9s} {'FullSER':>8s} {'Extra':>7s}")
for dim in ORDER:
    skw,sext,sv1=S[dim]; print(f"  {DISP[dim]:9s} {skw:8d} {sext:9d} {sv1:8d} {sv1-skw:+7d}")
print(f"  {'All':9s} {TK:8d} {TE:9d} {TV:8d} {TV-TK:+7d}")
print("\nRELATIVE (Keyword=100):")
print(f"  {'Category':9s} {'Keyword':>8s} {'+Extract':>9s} {'FullSER':>8s} {'Uplift':>7s}")
for dim in ORDER:
    skw,sext,sv1=S[dim]; print(f"  {DISP[dim]:9s} {100:8d} {pct(sext,skw):9.0f} {pct(sv1,skw):8.0f} {pct(sv1-skw,skw):+6.0f}%")
print(f"  {'All':9s} {100:8d} {pct(TE,TK):9.0f} {pct(TV,TK):8.0f} {pct(TV-TK,TK):+6.0f}%")
