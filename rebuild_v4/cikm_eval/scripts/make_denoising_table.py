"""
Residual-noise table: evidence the denoising is an ongoing, human-in-the-loop process.

We do NOT modify the deployed demo (v2). We report the residual noise facets STILL
PRESENT in the deployed demo (recipe-level, counted from the deployed exhibit) that the
LLM judge has flagged for the next round. This is the honest "iterative process" story:
the deployed v2 is a snapshot, not a finished artifact.

Reads the deployed exhibit; writes tables/denoising.tex.
"""
import json
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
EX = json.load(open("/Users/liliu/SER-DB/food-exhibit-data-500recipes.json"))["items"]
FIELD = {"taste_flavor":"taste_attributes","texture_mouthfeel":"texture_attributes",
         "meal_type":"meal_type_attributes","occasion_holiday":"occasion_attributes",
         "audience_enjoyment":"audience_attributes","cuisine_type":"type_attributes"}
DISP = {"taste_flavor":"Flavor","meal_type":"Meal","occasion_holiday":"Occasion","audience_enjoyment":"Audience"}
RESIDUAL = {
    "audience_enjoyment": ["self","us","others","you"],
    "occasion_holiday": ["occasion"],
}
WHY = {"self":"cook-vs-audience (reviewer themselves)","us":"first person plural",
       "others":"too generic","you":"second person","occasion":"category name, not a value"}

rows=[]
for d,terms in RESIDUAL.items():
    f=FIELD[d]
    for t in terms:
        n=sum(1 for it in EX if t in (it.get(f,[]) or []))
        if n>0: rows.append((DISP[d],t,n,WHY.get(t,"")))
rows.sort(key=lambda x:-x[2])

L=[]; a=L.append
a("% Auto-generated by scripts/make_denoising_table.py")
a("\\begin{table}[t]"); a("\\centering"); a("\\small"); a("\\setlength{\\tabcolsep}{5pt}")
a("\\begin{tabular}{@{}llrl@{}}")
a("\\toprule")
a("\\textbf{Dim.} & \\textbf{Residual facet} & \\textbf{Recipes} & \\textbf{Why it is noise} \\\\")
a("\\midrule")
for dim,t,n,why in rows:
    a(f"{dim} & {t} & {n} & {why} \\\\")
a("\\bottomrule"); a("\\end{tabular}")
a("\\caption{Denoising is iterative and human-in-the-loop. The deployed demo (v2) is a "
  "snapshot, not a finished artifact: the LLM judge has flagged these residual noise "
  "facets still present in it for the next round (the largest being the cook-vs-audience "
  "\\emph{self}, on 483 recipes). We leave the deployed demo unchanged and exclude these "
  "from the coverage analysis (Table~\\ref{tab:recall-4stage}) so the recall numbers reflect "
  "genuine merges. Earlier rounds already removed the bulk of the noise (generic praise such "
  "as \\emph{delicious}/\\emph{good}, and \\emph{everyone}/\\emph{people}); these are the remaining tail.}")
a("\\label{tab:denoising}"); a("\\end{table}")
(PAPER/"tables"/"denoising.tex").write_text("\n".join(L)+"\n")
print("Wrote tables/denoising.tex")
for r in rows: print("  ",r)
