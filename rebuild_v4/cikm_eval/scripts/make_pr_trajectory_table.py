"""
Precision-recall trajectory across the pipeline gradient (the IR-standard view).

One condensed, rich table: rows are the four pipeline stages
    Keyword baseline -> +LLM extraction -> +Normalization (v1) -> +Judge feedback (v2)
columns give pooled, independently-judged precision/recall for each of three
concepts, plus a macro-average P/R/F1. Reads from the pooled-PR judgments produced
by scripts/eval_pr_concept.py.

The story it encodes: precision is essentially constant down the column while
recall climbs, i.e. each stage moves the system rightward in precision-recall space
(more recall at the same precision). v1 and v2 coincide on these three concepts
because the judge-feedback blacklist (self, generic adjectives) does not intersect
their attribute sets; v2's precision effect is realized on other concepts (it removes
the spurious first-person "self" audience entirely).

Reads eval_data/pr_concept_judgments.jsonl ; writes tables/pr_trajectory.tex.
"""
import json
from collections import defaultdict
from pathlib import Path

PAPER = Path(__file__).resolve().parents[1]
rows = [json.loads(l) for l in open(PAPER/"eval_data"/"pr_concept_judgments.jsonl")]

CONCEPTS = ["spicy","mother","kids"]
STAGES = [("keyword","Keyword baseline"),("gemma","\\;+ LLM extraction"),
          ("v1","\\;+ Normalization"),("v2","\\;+ Judge feedback")]

# per concept: gold set + per-method P/R/F
per = {}
for c in CONCEPTS:
    cr = [r for r in rows if r["concept"]==c and "error" not in r["judgment"]]
    gold = {r["recipe_id"] for r in cr if r["judgment"].get("applies")}
    per[c] = {}
    for m,_ in STAGES:
        ret = {r["recipe_id"] for r in cr if r["in"].get(m)}
        tp = len(ret & gold)
        P = 100*tp/len(ret) if ret else 0.0
        R = 100*tp/len(gold) if gold else 0.0
        F = 2*P*R/(P+R) if P+R else 0.0
        per[c][m] = (P,R,F)

def macro(m):
    Ps=[per[c][m][0] for c in CONCEPTS]; Rs=[per[c][m][1] for c in CONCEPTS]; Fs=[per[c][m][2] for c in CONCEPTS]
    return sum(Ps)/3, sum(Rs)/3, sum(Fs)/3

L=[]; a=L.append
a("% Auto-generated by scripts/make_pr_trajectory_table.py")
a("\\begin{table}[t]"); a("\\centering"); a("\\small"); a("\\setlength{\\tabcolsep}{3.5pt}")
a("\\begin{tabular}{@{}lcccccccc@{}}")
a("\\toprule")
a("& \\multicolumn{2}{c}{\\textbf{Spicy}} & \\multicolumn{2}{c}{\\textbf{Mother}} & \\multicolumn{2}{c}{\\textbf{Kids}} & \\multicolumn{2}{c}{\\textbf{Macro}} \\\\")
a("\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}\\cmidrule(lr){6-7}\\cmidrule(lr){8-9}")
a("\\textbf{Stage} & P & R & P & R & P & R & R & F1 \\\\")
a("\\midrule")
for m,label in STAGES:
    cells=[]
    for c in CONCEPTS:
        P,R,_=per[c][m]; cells += [f"{P:.0f}",f"{R:.0f}"]
    mp,mr,mf=macro(m)
    cells += [f"\\textbf{{{mr:.0f}}}", f"\\textbf{{{mf:.0f}}}"]
    a(f"{label} & " + " & ".join(cells) + " \\\\")
a("\\bottomrule"); a("\\end{tabular}")
a("\\caption{Precision/recall along the pipeline, pooled and judged independently "
  "(gpt-oss rules whether each concept genuinely applies, respecting negation and "
  "irrelevant mentions). Down each column precision is essentially constant while "
  "recall climbs (macro recall $74\\to88\\to93$), so every stage moves the system "
  "rightward in precision-recall space rather than trading one for the other. "
  "The keyword baseline matches the exact word in reviews; LLM extraction resolves "
  "read-time synonyms (mother recall $49\\to95$); normalization merges the remaining "
  "surface variants (spicy $76\\to90$). v1 and v2 coincide here because the "
  "judge-feedback blacklist does not intersect these three concepts; its precision "
  "effect appears on other concepts, e.g. removing the spurious first-person "
  "\\emph{self} audience. Pooled recall (TREC assumption).}")
a("\\label{tab:pr-trajectory}"); a("\\end{table}")
(PAPER/"tables"/"pr_trajectory.tex").write_text("\n".join(L)+"\n")
print("Wrote tables/pr_trajectory.tex\n")
print(f"{'Stage':20s} | spicy P/R | mother P/R | kids P/R | Macro P/R/F1")
for m,label in STAGES:
    cells=" | ".join(f"{per[c][m][0]:.0f}/{per[c][m][1]:.0f}" for c in CONCEPTS)
    mp,mr,mf=macro(m)
    print(f"{label.replace(chr(92)+';',''):20s} | {cells} | {mp:.0f}/{mr:.0f}/{mf:.0f}")
